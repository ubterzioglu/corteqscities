def merge_rules(base: dict[str, Any], override: dict[str, Any]) -> dict[str, Any]:
    """Derin birlestirme; girdileri degistirmez."""
    merged = copy.deepcopy(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = merge_rules(merged[key], value)
        else:
            merged[key] = copy.deepcopy(value)
    return merged


def fold(text: Any) -> str:
    """Kucuk harf, aksansiz, harf-rakam disi -> bosluk."""
    raw = unicodedata.normalize("NFKD", str(text or ""))
    raw = "".join(ch for ch in raw if not unicodedata.combining(ch)).lower()
    return re.sub(r"[^a-z0-9]+", " ", raw).strip()


@lru_cache(maxsize=512)
def _word_re(pattern: str) -> re.Pattern[str]:
    return re.compile(rf"\b(?:{pattern})\b")


def first_hit(patterns: list[str], text: str) -> str | None:
    for pattern in patterns:
        match = _word_re(pattern).search(text)
        if match:
            return match.group(0)
    return None


def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dphi, dlmb = p2 - p1, math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dlmb / 2) ** 2
    return 6371.0 * 2 * math.asin(math.sqrt(min(1.0, a)))


def _finding(code: str, severity: str, detail: str) -> dict[str, str]:
    return {"code": code, "severity": severity, "detail": detail}


def check_license(c: dict, e: dict | None, rules: dict, ctx: dict) -> list[dict]:
    lic = fold(c.get("license"))
    cfg = rules["license"]
    found = []
    if not lic or first_hit(cfg["deny"], lic) or not any(re.search(p, lic) for p in cfg["allow"]):
        found.append(_finding("license_not_allowed", "reject", f"lisans '{c.get('license') or '-'}' izinli listede degil"))
    if str(c.get("restrictions") or "").strip():
        found.append(_finding("restrictions", "flag", f"Commons kisiti: {c['restrictions']}"))
    return found


def check_file(c: dict, e: dict | None, rules: dict, ctx: dict) -> list[dict]:
    found = []
    mime = c.get("mime")
    if mime and mime not in rules["mime"]["allowed"]:
        found.append(_finding("mime_not_allowed", "reject", f"dosya turu {mime}"))
    width, height = c.get("width") or 0, c.get("height") or 0
    if width and height:
        cfg = rules["resolution"]
        short, long_ = min(width, height), max(width, height)
        if long_ / short > cfg["panorama_ratio"]:
            found.append(_finding("panorama", "flag", f"en-boy orani {long_ / short:.1f} (kirpma sonrasi kisa kenar dar)"))
        elif short < cfg["min_short_side"]:
            found.append(_finding("low_resolution", "flag", f"kisa kenar {short}px < {cfg['min_short_side']}"))
    return found


def check_art(c: dict, e: dict | None, rules: dict, ctx: dict) -> list[dict]:
    cfg = rules["art"]
    venue_text = fold(" ".join(str(v or "") for v in [(e or {}).get("name"), (e or {}).get("group")]))
    if first_hit(cfg.get("except_if", []), f"{ctx['text']} {venue_text}"):
        return []  # duvar resmi / street-art mekani: eser fotografi rights_review'a kalir
    hit = first_hit(cfg["patterns"], ctx["text"])
    if hit:
        return [_finding("art_not_photo", "reject", f"eser/cizim isareti: '{hit}'")]
    if re.search(cfg["lifespan"], str(c.get("title") or "")):
        return [_finding("art_not_photo", "reject", "basliktaki sanatci yasam araligi (eser reprodüksiyonu)")]
    return []


def check_ai(c: dict, e: dict | None, rules: dict, ctx: dict) -> list[dict]:
    hit = first_hit(rules["ai"]["patterns"], ctx["text"])
    return [_finding("ai_generated", "reject", f"sentetik goruntu isareti: '{hit}'")] if hit else []


def _target_terms(e: dict, rules: dict) -> tuple[list[str], list[str]]:
    """(belediye terimleri, mekan adi terimleri) katlanmis bicimde."""
    cfg = rules["place"]
    towns = [fold(t) for t in [e.get("municipality"), *(e.get("municipality_aliases") or [])] if fold(t)]
    names = [fold(t) for t in [e.get("name"), *(e.get("aliases") or [])] if fold(t)]
    generic = set(cfg["generic_name_tokens"]) | set(towns)
    tokens = [tok for name in names for tok in name.split() if len(tok) >= cfg["min_token_len"] and tok not in generic]
    return towns, sorted(set(names + tokens))


def _foreign_places(c: dict, towns: list[str], names: list[str], rules: dict, text: str) -> list[str]:
    cfg = rules["place"]
    targets = towns + names
    places = []
    for category in c.get("categories") or []:
        for pattern in cfg["category_patterns"]:
            match = re.search(pattern, category.strip())
            if match:
                places.append(fold(re.sub(r"\s*\([^)]*\)", "", match.group(1))))
    places += [fold(p) for p in cfg["known_other_places"] if first_hit([re.escape(fold(p))], text)]
    ignore = {fold(p) for p in cfg["ignore_places"]}
    return sorted({p for p in places if p and p not in ignore and not any(t in p or p in t for t in targets)})


def check_place(c: dict, e: dict | None, rules: dict, ctx: dict) -> list[dict]:
    """Belediye adi (on ek olarak da: 'Eindhovens') yoksa ve baska yer varsa reject; hicbir hedef ad yoksa flag.

    Mekan adi tek basina baska yer kanitini yenmez: sokak adlari ('Kruisstraat') pek cok kasabada vardir.
    """
    towns, names = _target_terms(e, rules)
    text = ctx["text"]
    ctx["name_match"] = bool(first_hit([re.escape(n) for n in names], text)) if names else False
    town_match = bool(towns and first_hit([re.escape(t) + r"\w*" for t in towns], text))
    if town_match:
        return []
    foreign = _foreign_places(c, towns, names, rules, text)
    if foreign:
        return [_finding("other_place", "reject", f"belediye adi yok, baska yer var: {', '.join(foreign)}")]
    if ctx["name_match"]:
        return []
    return [_finding("place_mismatch", "flag", "baslik/aciklama/kategorilerde belediye veya mekan adi yok")]


def check_name_extension(c: dict, e: dict | None, rules: dict, ctx: dict) -> list[dict]:
    """Kaynak adinda mekan adi bir baglac ve yeni bir adla uzuyorsa flag (Sevilla S01: '... San Vicente de Paul').

    Sehir/semt adi, mekanin kendi ad sozcukleri, sayi ve betimleme ('de noche') uzanti sayilmaz.
    """
    cfg = rules["place"]
    full = [fold(t) for t in [e.get("name"), *(e.get("aliases") or [])] if fold(t)]
    known = {tok for name in full for tok in name.split()}
    known |= {tok for t in [e.get("municipality"), *(e.get("municipality_aliases") or []), e.get("district")]
              for tok in fold(t).split()}
    connectors = "|".join(re.escape(x) for x in sorted(cfg["name_connectors"], key=len, reverse=True))
    for name in sorted(full, key=len, reverse=True):
        for match in re.finditer(rf"\b{re.escape(name)} ({connectors}) ([a-z]{{3,}})\b", ctx["text"]):
            word = match.group(2)
            if word not in known and word not in cfg["name_descriptors"]:
                return [_finding("name_extended", "flag",
                                 f"kaynak adi mekan adindan uzun: '{match.group(0)}' (baska yapi olabilir)")]
    return []


def check_gps(c: dict, e: dict | None, rules: dict, ctx: dict) -> list[dict]:
    lat, lon = c.get("lat"), c.get("lon")
    if lat is None or lon is None:
        return []
    cfg = rules["place"]
    if e.get("lat") is not None and e.get("lon") is not None:
        km = haversine_km(lat, lon, e["lat"], e["lon"])
        if km > cfg["gps_reject_km"]:
            return [_finding("gps_far", "reject", f"GPS mekana {km:.1f} km (> {cfg['gps_reject_km']})")]
        if km > cfg["gps_flag_km"]:
            return [_finding("gps_far", "flag", f"GPS mekana {km:.1f} km")]
        return []
    if e.get("city_lat") is not None and e.get("city_lon") is not None:
        km = haversine_km(lat, lon, e["city_lat"], e["city_lon"])
        if km > cfg["city_reject_km"]:
            return [_finding("gps_far", "reject", f"GPS sehir merkezine {km:.1f} km (> {cfg['city_reject_km']})")]
    return []


def check_archive(c: dict, e: dict | None, rules: dict, ctx: dict) -> list[dict]:
    cfg = rules["archive"]
    years = [c["year"]] if isinstance(c.get("year"), int) else []
    for category in c.get("categories") or []:
        for pattern in cfg["category_year_patterns"]:
            match = re.search(pattern, category.strip(), flags=re.IGNORECASE)
            if match:
                years.append(int(match.group(1)))
    oldest = min(years) if years else None
    if oldest is not None and oldest < cfg["before_year"]:
        return [_finding("archive", "flag", f"cekim yili {oldest} < {cfg['before_year']}: tarihli altyazi gerekir")]
    return []


def _keyword_check(code: str, section: str, detail: str):
    def check(c: dict, e: dict | None, rules: dict, ctx: dict) -> list[dict]:
        name_text = " ".join(fold(t) for t in [e.get("name"), *(e.get("aliases") or [])])
        for pattern in rules[section]["patterns"]:
            match = _word_re(pattern).search(ctx["text"])
            if match and not _word_re(pattern).search(name_text):
                return [_finding(code, "flag", f"{detail}: '{match.group(0)}'")]
        return []
    return check


def check_rights(c: dict, e: dict | None, rules: dict, ctx: dict) -> list[dict]:
    hit = first_hit(rules["rights"]["patterns"], ctx["text"])
    return [_finding("rights_review", "flag", f"kisi/eser haklari incelemesi: '{hit}'")] if hit else []


def check_geosearch(c: dict, e: dict | None, rules: dict, ctx: dict) -> list[dict]:
    """check_place'ten sonra calisir (ctx['name_match'])."""
    cfg = rules["geosearch"]
    if c.get("query_kind") not in cfg["query_kinds"] or ctx.get("name_match"):
        return []
    return [_finding("geosearch_unconfirmed", cfg["severity"], "yalniz koordinat yakinligiyla bulundu; mekan adi metinde yok")]


ENTRY_CHECKS = (check_place, check_name_extension, check_geosearch, check_gps, check_archive,
                _keyword_check("detail_interior", "detail", "detay/ic mekan"),
                _keyword_check("statue_subject", "statue", "heykel/anit konusu"),
                _keyword_check("off_subject", "off_subject", "konu disi altyapi"), check_rights)
BASE_CHECKS = (check_license, check_file, check_art, check_ai)


def _escalate(findings: list[dict], role: str, rules: dict) -> list[dict]:
    codes = set(rules["role_escalation"].get(role, []))
    return [{**f, "severity": "reject", "detail": f"{f['detail']} (rol {role})"} if f["code"] in codes else f for f in findings]


def _score(findings: list[dict], c: dict, ctx: dict, rules: dict) -> int:
    cfg = rules["score"]
    score = cfg["base"] - sum(cfg[f["severity"]] for f in findings)
    score += cfg["name_bonus"] if ctx.get("name_match") else 0
    short = min(c.get("width") or 0, c.get("height") or 0)
    return score + (cfg["hires_bonus"] if short >= cfg["hires_side"] else 0)


def evaluate(c: dict[str, Any], e: dict[str, Any] | None, rules: dict[str, Any]) -> dict[str, Any]:
    """Tek aday -> {decision keep|flag|reject, reasons [kod], notes [kod: aciklama], score}."""
    text = fold(" ".join([str(c.get("title") or ""), str(c.get("description_text") or ""), *(c.get("categories") or [])]))
    ctx: dict[str, Any] = {"text": text}
    findings = [f for check in BASE_CHECKS for f in check(c, e, rules, ctx)]
    if e is None:
        findings.append(_finding("no_plan_entry", "flag", f"planda entry yok: {c.get('entry_id')}"))
    else:
        findings += _escalate([f for check in ENTRY_CHECKS for f in check(c, e, rules, ctx)], e.get("role", "venue"), rules)
    severities = {f["severity"] for f in findings}
    decision = "reject" if "reject" in severities else "flag" if "flag" in severities else "keep"
    return {"candidate_id": c.get("candidate_id"), "entry_id": c.get("entry_id"), "decision": decision,
            "reasons": list(dict.fromkeys(f["code"] for f in findings)),
            "notes": [f"{f['code']}[{f['severity']}]: {f['detail']}" for f in findings],
            "score": _score(findings, c, ctx, rules)}
